#include<stdio.h>
int main()
{
	int branch=4;
	switch(branch)
    {
    	case 1:
    		printf("CSE");
    		break;
    	case 2:
    		printf("AIML");
    		break;
    	case 3:
    		printf("AIDS");
    		break;
    	case 4:
    		printf("IT");
    		break;
    	case 5:
    	    printf("ECE");
    	    break;
    	default:
    	    printf("Invalid branch");
    	    
    	return 0;
    	
	}
}
